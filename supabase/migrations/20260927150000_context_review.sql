--
-- hidden — на пример пожаловались («Пожаловаться на пример»): больше не
-- показывается никому; reported_at — когда.
--
-- Кэш создан до проверки перевода (второй проход дешёвой моделью) — в нём
-- встречались корявые переводы («Эта обувь очень новая»). Это только кэш,
-- общий на всех: удаляем заказы (предложения уходят каскадом), при следующих
-- занятиях всё сгенерируется заново уже с проверкой.

alter table public.context_sentences
  add column hidden      boolean     not null default false,
  add column reported_at timestamptz;

