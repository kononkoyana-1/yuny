/**
 * Годится ли строка БКРС как значение: в вариантах ответа, в заметках о
 * знаках, в составе слова. В словаре попадаются пометки без смысла («гл. А»,
 * «сущ.»), отсылки («вм. 酒», «см. 说», «употребляется вместо какого-то
 * иероглифа») и узкие значения (история, география, имена) — их ученику
 * показывать нельзя или только в конце списка.
 */

/** Пометка вместо значения: «гл. А», «сущ.», «собств.». */
export const LABEL_ONLY =
  /^(гл|сущ|прил|нареч|наречие|числ|мест|служ|словообр|собств|счётн|сч\. ?сл|межд|союз|предлог|частица|глагол)\.?(\s+[А-ЯA-Z]\.?)?$/i;

/** Узкое или книжное значение — в конец списка: история, география, диалект, «*», имена. */
export const NARROW = /^(\*|ист\.|геогр\.|уст\.|диал\.|книжн\.|собств\.|см\.|вм\.|Примечание)|\(фамилия\)|фамилия\)?$/i;

/** Отсылка к другому знаку или слову — не значение вовсе. */
const REFERENCE = /(^|\s)(вм\.|см\.|то же,? что)|вместо\b|иероглиф/i;

/**
 * Короткое значение для варианта ответа: первый пункт до «;», без пометки
 * «*». Пометка, отсылка, узкое или слишком длинное — `null`, берётся другой
 * кандидат.
 */
export function usableGloss(gloss: string | null): string | null {
  if (!gloss) return null;
  const first = gloss.split(";")[0].replace(/^\*\s*/, "").trim();
  if (!/[А-Яа-яЁё]/.test(first) || first.length > 40) return null;
  if (LABEL_ONLY.test(first) || NARROW.test(first) || REFERENCE.test(first)) return null;
  return first;
}
