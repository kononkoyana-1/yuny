/**
 * Связь до api.github.com рвётся: чтение проходит, запись то и дело отваливается
 * по таймауту. Поэтому каждый вызов повторяется — без этого скрипт падает на
 * первой же метке и приходится начинать заново.
 */
function gh(args, { allowFail = false, attempts = 6, input } = {}) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return execFileSync("gh", args, {
        encoding: "utf8",
        input,
        stdio: [input === undefined ? "ignore" : "pipe", "pipe", "pipe"],
      }).trim();
    } catch (error) {
      lastError = error;
      const message = String(error.stderr || "");
      const retriable = /timeout|reset|EOF|502|503|504|rate limit/i.test(message);
      if (!retriable || attempt === attempts) break;
      const waitMs = 2000 * attempt;
      process.stdout.write(`    попытка ${attempt} не прошла, жду ${waitMs / 1000}с\n`);
      execFileSync("sleep", [String(waitMs / 1000)]);
    }
  }
  if (allowFail) return null;
  throw lastError;
}

/**
 * Тело задачи = описание из ISSUES плюс чек-лист шагов. Чек-лист живёт в теле,
 * а не отдельными задачами: GitHub сам считает по нему прогресс («3 of 7»), и
 * список видно в ленте, не открывая каждую задачу.
 */
function renderBody(issue) {
  const steps = STEPS[issue.title];
  if (!steps || steps.length === 0) return issue.body;
  return `${issue.body}\n\n## Шаги\n\n${steps.map((s) => `- [ ] ${s}`).join("\n")}`;
}

function ensureLabels() {
  for (const [name, color, description] of LABELS) {
    if (DRY) { console.log(`  метка ${name}`); continue; }
    gh(["label", "create", name, "--color", color, "--description", description, "--force"]);
    console.log(`  метка ${name}`);
  }
}

function ensureMilestones() {
  const existing = DRY
    ? new Set()
    : new Set(
        JSON.parse(gh(["api", "repos/{owner}/{repo}/milestones?state=all"]) || "[]").map((m) => m.title),
      );
  for (const [title, description] of MILESTONES) {
    if (existing.has(title)) { console.log(`  веха ${title} — уже есть`); continue; }
    if (DRY) { console.log(`  веха ${title}`); continue; }
    gh(["api", "repos/{owner}/{repo}/milestones", "-f", `title=${title}`, "-f", `description=${description}`]);
    console.log(`  веха ${title}`);
  }
}

function createIssues() {
  // Пробный прогон не ходит в сеть вообще: его можно запустить там, где
  // GitHub недоступен, чтобы просто посмотреть состав бэклога.
  const existing = DRY
    ? new Map()
    : new Map(
        JSON.parse(
          gh(["issue", "list", "--state", "all", "--limit", "300", "--json", "title,number"]) || "[]",
        ).map((i) => [i.title, i.number]),
      );

  let created = 0;
  let updated = 0;
  for (const issue of ISSUES) {
    const known = existing.get(issue.title);
    if (known) {
      if (DRY) {
        console.log(`  обновить #${known}: ${issue.title}`);
        continue;
      }
      gh(["issue", "edit", String(known), "--body-file", "-"], { input: renderBody(issue) });
      console.log(`  #${known} обновлена: ${issue.title}`);
      updated += 1;
      continue;
    }
    const labels = [`фаза-${issue.phase}`, ...issue.labels];
    const milestone = MILESTONES[issue.phase][0];
    if (DRY) {
      console.log(`  + [${labels.join(", ")}] ${issue.title}`);
      continue;
    }
    const url = gh([
      "issue", "create",
      "--title", issue.title,
      "--body", renderBody(issue),
      "--milestone", milestone,
      ...labels.flatMap((l) => ["--label", l]),
    ]);
    created += 1;
    console.log(`  ${url}`);
  }
  return { created, updated };
}

