console.log("Метки:");
ensureLabels();
console.log("\nВехи:");
ensureMilestones();
console.log("\nЗадачи:");
const { created, updated } = createIssues();
console.log(
  `\nГотово. Задач: ${ISSUES.length}, создано: ${DRY ? 0 : created}, обновлено: ${DRY ? 0 : updated}.`,
);
